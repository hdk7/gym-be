/**
 * Builds curriculum items strictly mapped from the 15 reusable class programs.
 */
const buildCurriculumFromSeed = (offset = 0) => {
  return Array.from({ length: 12 }, (_, i) => {
    const cls = SEED_CLASSES[(i + offset) % SEED_CLASSES.length];
    return {
      classNumber: i + 1,
      classId: cls.id,
      className: cls.name,
      subject: cls.name,
      message: `Beginner: ${cls.beginnerWorkouts}\nIntermediate: ${cls.intermediateWorkouts}`,
      beginnerWorkouts: cls.beginnerWorkouts,
      intermediateWorkouts: cls.intermediateWorkouts,
    };
  });
};

